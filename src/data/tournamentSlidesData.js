/**
 * Returns 20 curated 16:9 slides tailored to the tournament game.
 */
export function getGameSlidesForTournament(tournament) {
  if (!tournament) return VALORANT_GAME_SLIDES_20;

  // 1. If tournament explicitly has gameSlides in CMS / state
  if (Array.isArray(tournament.gameSlides) && tournament.gameSlides.length > 0) {
    return tournament.gameSlides.slice(0, 20);
  }

  const gameLower = (tournament.game || '').toLowerCase();
  const titleLower = (tournament.title || '').toLowerCase();

  // 2. RoV / Arena of Valor
  if (gameLower.includes('rov') || gameLower.includes('valor') && gameLower.includes('arena') || titleLower.includes('rov')) {
    return ROV_GAME_SLIDES_20;
  }

  // 3. CS2 / Counter-Strike
  if (gameLower.includes('cs2') || gameLower.includes('counter-strike') || titleLower.includes('cs2') || titleLower.includes('counter-strike')) {
    return CS2_GAME_SLIDES_20;
  }

  // 4. VALORANT
  if (gameLower.includes('valorant') || titleLower.includes('valorant')) {
    return VALORANT_GAME_SLIDES_20;
  }

  // 5. Default fallback to 20 slides
  return VALORANT_GAME_SLIDES_20;
}
